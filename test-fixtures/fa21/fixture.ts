import { readFileSync } from 'node:fs';
import { Parser, assertMichelsonContract } from '@taquito/michel-codec';
import { ScriptResponse, EntrypointsResponse } from '@taquito/rpc';

export const fa21Owner = 'tz1KqTpEZ7Yob7QbPE4Hy4Wo8fHG8LhKxZSx';
export const fa21Recipient = 'tz1gjaF81ZRRvdzjobyfVNsAeSC6PScjfQwN';
export const fa21Address = 'KT1RJ6PbjHpwc3M5rw5s2Nbmefwbuwbdxton';

export function fa21Code(): ScriptResponse['code'] {
  const parsed = new Parser().parseJSON(
    JSON.parse(readFileSync(new URL('./reference.json', import.meta.url), 'utf8'))
  );
  if (!assertMichelsonContract(parsed))
    throw new Error('FA2.1 reference is not a Michelson contract');
  return parsed;
}

// Fixed Octez entrypoint response for the pinned script, not generated by Taquito.
export const fa21Entrypoints: EntrypointsResponse = JSON.parse(
  readFileSync(new URL('./entrypoints.json', import.meta.url), 'utf8')
);

export function fa21InitialStorage(owner = fa21Owner): string {
  return `Pair { Elt (Pair "${owner}" 0) 100 } { Elt 0 100 } {} {} { Elt 0 (Pair 0 {}) }`;
}
